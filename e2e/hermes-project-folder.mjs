import assert from "node:assert/strict";
import { chromium } from "playwright";
import nextEnv from "@next/env";
import { createWebSessionToken } from "../lib/web-auth.ts";
import { mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

nextEnv.loadEnvConfig(process.cwd(), true, { info() {}, error() {} });
const origin = process.env.HERMES_TEST_URL ?? "http://127.0.0.1:30142";
const browser = await chromium.launch({ headless: true, channel: "msedge" });
const context = await browser.newContext({ viewport: { width: 1365, height: 900 }, reducedMotion: "reduce" });
await context.addCookies([{ name: "pi_web_session", value: createWebSessionToken(process.env.PI_WEB_PASSWORD), url: origin }]);
await context.addInitScript(() => localStorage.setItem("hermes-recent-projects", JSON.stringify(["/projects/Beta"])));
const page = await context.newPage();
const errors = [], projectRequests = [], chatRequests = [], apiRuns = [];
page.on("pageerror", error => errors.push(error.message));
let failProject = false, failAfterStart = false, releaseProject, releaseChat;
let projectGate = Promise.resolve(), chatGate = Promise.resolve();
await page.route("**/api/hermes-session/project", async route => {
  const body = route.request().postDataJSON(); projectRequests.push(body);
  await projectGate;
  await route.fulfill(failProject ? { status: 502, json: { error: "目录切换失败" } } : { json: { cwd: body.cwd, branch: "main" } });
});
await page.route("**/api/hermes-session/chat", async route => {
  const body = route.request().postDataJSON(); chatRequests.push(body);
  await chatGate;
  if (failAfterStart) {
    await route.fulfill({ contentType: "text/event-stream", body: 'data: {"event":"run.started","run_id":"native-failed-run","session_id":"project-session"}\n\ndata: {"event":"run.failed","error":"Fixture accepted run failed"}\n\n' });
    return;
  }
  await route.fulfill({ contentType: "text/event-stream", body: 'data: {"event":"run.started","run_id":"native-run","session_id":"project-session"}\n\ndata: {"event":"message.delta","delta":"Project answer"}\n\ndata: {"event":"run.completed","output":"Project answer"}\n\n' });
});
await page.route("**/api/cwd/browse**", route => route.fulfill({ json: { path: "/projects/Alpha", parentPath: "/projects", directories: [] } }));
await page.route("**/api/cwd/validate", route => {
  const cwd = route.request().postDataJSON().cwd;
  return route.fulfill(cwd === "/missing" ? { status: 400, json: { error: "Missing folder" } } : { json: { cwd } });
});
await page.route("**/api/git/status**", route => route.fulfill({ json: { isGit: false, files: [], supported: false } }));
await page.route("**/api/file-index**", route => route.fulfill({ json: { files: [] } }));
await page.route("**/api/files/**", route => route.fulfill({ json: { entries: [] } }));
await page.route("**/api/hermes/**", async route => {
  const path = new URL(route.request().url()).pathname.replace("/api/hermes", "");
  let data = { ok: true };
  if (path === "/v1/models") data = { data: [{ id: "fixture-model" }] };
  else if (path === "/api/model/options") data = { providers: [] };
  else if (path === "/api/sessions") data = { sessions: [{ id: "project-session", title: "Project chat" }, { id: "plain", title: "Ordinary chat" }, { id: "missing", title: "Unavailable project" }] };
  else if (path.endsWith("/messages")) data = { messages: [{ role: "user", content: "Question" }, { role: "assistant", content: "Existing answer" }] };
  else if (path === "/api/sessions/project-session") data = { id: "project-session", model: "fixture-model", model_config: JSON.stringify({ provider: "custom:api" }), billing_provider: "custom", cwd: "/projects/Alpha", git_branch: "main" };
  else if (path === "/api/sessions/missing") data = { id: "missing", model: "fixture-model", cwd: "/missing" };
  else if (path === "/api/sessions/plain") data = { id: "plain", model: "fixture-model" };
  else if (path === "/v1/runs") { apiRuns.push(route.request().postDataJSON()); data = { run_id: "ordinary-run", session_id: "plain" }; }
  else if (path.endsWith("/events")) { await route.fulfill({ contentType: "text/event-stream", body: 'data: {"event":"run.completed","output":"Ordinary answer"}\n\n' }); return; }
  await route.fulfill({ json: data });
});
const picker = page.getByRole("button", { name: "选择项目文件夹", exact: true });
const textarea = page.locator(".chat-input-textarea");
const out = join(tmpdir(), "hermes-web-qa"); await mkdir(out, { recursive: true });
try {
  await page.goto(origin);
  await page.waitForFunction(() => !document.querySelector(".hermes-project-trigger").disabled);
  assert.equal(await page.locator(".hermes-project-branch").count(), 0);
  assert.equal(await page.getByRole("button", { name: "文件浏览器", exact: true }).getAttribute("aria-expanded"), "false");
  await picker.click(); await page.getByRole("button", { name: "浏览文件夹…", exact: true }).click();
  projectGate = new Promise(resolve => { releaseProject = resolve; });
  await page.locator(".directory-picker-footer .directory-picker-action").last().click();
  await page.waitForFunction(() => document.querySelector(".hermes-project-trigger").disabled);
  assert.equal(await picker.textContent(), "选择项目文件夹");
  releaseProject();
  await page.waitForFunction(() => document.querySelector(".hermes-project-trigger").textContent.includes("Alpha"));
  assert.equal(await picker.getAttribute("title"), "/projects/Alpha");
  assert.equal(projectRequests[0].session_id, undefined, "folder selection must not create a chat");
  assert.equal(await page.getByRole("button", { name: "文件浏览器", exact: true }).getAttribute("aria-expanded"), "true");
  chatGate = new Promise(resolve => { releaseChat = resolve; });
  const sentProject = page.waitForRequest(request => request.url().endsWith("/api/hermes-session/chat"));
  await textarea.fill("Inspect folder"); await textarea.press("Enter");
  await page.waitForFunction(() => document.querySelector(".hermes-project-trigger").disabled);
  await sentProject;
  releaseChat();
  await page.getByText("Project answer", { exact: true }).waitFor();
  assert.equal(chatRequests[0].cwd, "/projects/Alpha"); assert.equal(apiRuns.length, 0);
  failProject = true;
  await picker.click(); await page.getByRole("button", { name: "Beta", exact: true }).click();
  await page.getByText("目录切换失败", { exact: true }).waitFor();
  assert.equal(await picker.getAttribute("title"), "/projects/Alpha");
  assert.equal(projectRequests.at(-1).session_id, "project-session");
  await page.keyboard.press("Escape");
  await page.screenshot({ path: join(out, "project-folder-desktop.png") });
  await page.getByRole("navigation", { name: "会话", exact: true }).getByRole("button", { name: /^Ordinary chat \d/ }).click();
  await page.getByText("Existing answer", { exact: true }).waitFor();
  await page.waitForFunction(() => !document.querySelector(".hermes-project-trigger").disabled);
  assert.equal(await picker.getAttribute("title"), "选择项目文件夹");
  await textarea.fill("Ordinary message"); await textarea.press("Enter");
  await page.getByText("Ordinary answer", { exact: true }).waitFor();
  assert.equal(apiRuns.length, 1);
  await page.getByRole("navigation", { name: "会话", exact: true }).getByRole("button", { name: /^Project chat \d/ }).click();
  await page.waitForFunction(() => document.querySelector(".hermes-project-trigger").title === "/projects/Alpha");
  await textarea.fill("Continue with custom provider"); await textarea.press("Enter");
  await page.getByText("Project answer", { exact: true }).waitFor();
  assert.equal(chatRequests.at(-1).provider, "custom:api");
  assert.equal(chatRequests.at(-1).session_id, "project-session");
  failAfterStart = true;
  await textarea.fill("Accepted before first delta"); await textarea.press("Enter");
  await page.getByText("Fixture accepted run failed", { exact: true }).waitFor();
  assert.equal(await textarea.inputValue(), "", "an accepted run must not be restored as an unsent prompt");
  assert.equal(await page.getByText("Accepted before first delta", { exact: true }).count(), 1);
  assert.equal(await page.evaluate(() => sessionStorage.getItem("hermes-active-run")), null);
  failAfterStart = false;
  await page.getByRole("navigation", { name: "会话", exact: true }).getByRole("button", { name: /^Unavailable project \d/ }).click();
  await page.getByText("此会话的项目文件夹无法访问，请重新选择文件夹。", { exact: true }).waitFor();
  await textarea.fill("Do not use previous project"); await textarea.press("Enter");
  await page.waitForFunction(() => document.querySelector(".chat-input-textarea").value === "Do not use previous project");
  assert.equal(chatRequests.length, 3); assert.equal(apiRuns.length, 1);
  failProject = false;
  await page.getByRole("button", { name: "新建对话", exact: true }).click();
  await page.locator(".directory-picker-footer .directory-picker-action").last().click();
  await page.locator(".hermes-session-row.active").getByText("草稿", { exact: true }).waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "打开侧栏", exact: true }).click();
  await picker.click();
  await page.screenshot({ path: join(out, "project-folder-mobile.png") });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(errors, []);
  console.log("Project folder: compact picker, confirmation, failed switch, native cwd, session restore, missing folder, ordinary chat and mobile passed.");
} finally { await browser.close(); }

import assert from "node:assert/strict";
import { chromium } from "playwright";
import nextEnv from "@next/env";
import { createWebSessionToken } from "../lib/web-auth.ts";
import { mkdir } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

nextEnv.loadEnvConfig(process.cwd(), true, { info() {}, error() {} });
const origin = process.env.HERMES_TEST_URL ?? "http://127.0.0.1:30142";
const browser = await chromium.launch({ headless: true, channel: "msedge" });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, reducedMotion: "reduce" });
await context.addCookies([{ name: "pi_web_session", value: createWebSessionToken(process.env.PI_WEB_PASSWORD), url: origin }]);
const page = await context.newPage();
const errors = [], writes = [];
let current = { provider: "deepseek", model: "shared-model" };
const customModels = ["shared-model", ...Array.from({ length: 85 }, (_, i) => `fixture-model-${i}`), "a-very-long-model-name-that-must-fit-inside-the-compact-dropdown-and-card"];
const endpoint = { id: "custom-fixture", name: "自定义接口", base_url: "https://models.example.test/v1", model: "shared-model", models: customModels, has_api_key: true };
page.on("pageerror", error => errors.push(error.message));
await page.route("**/api/hermes/**", async route => {
  const req = route.request(), url = new URL(req.url()), path = url.pathname.replace("/api/hermes", "");
  const body = req.postData() ? JSON.parse(req.postData()) : undefined;
  let data = { ok: true };
  if (req.method() !== "GET") writes.push({ path, body });
  if (path === "/v1/models") data = { data: [{ id: "hermes-agent" }] };
  else if (path === "/api/sessions") data = { sessions: [] };
  else if (path === "/api/providers/custom-endpoints") data = { endpoints: [{ ...endpoint, is_current: current.provider === endpoint.id }] };
  else if (path === "/api/providers/custom-endpoints/discover") data = { ok: true, models: customModels };
  else if (path === "/api/model/options") data = { ...current, providers: [{ slug: "deepseek", name: "DeepSeek", models: ["shared-model", "deepseek-reasoner"], is_current: current.provider === "deepseek", authenticated: true, api_url: "https://api.deepseek.com/v1" }, { slug: "anthropic", name: "Anthropic", models: ["claude-fixture"], key_env: "ANTHROPIC_API_KEY", authenticated: true }, { slug: "custom-fixture", name: "自定义接口", is_user_defined: true, models: customModels }] };
  else if (path === "/api/providers/oauth") data = { providers: [] };
  else if (path === "/api/model/set") { current = { provider: body.provider, model: body.model }; }
  await route.fulfill({ json: data });
});
const out = join(tmpdir(), "hermes-web-qa");
await mkdir(out, { recursive: true });
try {
  await page.goto(origin);
  await page.getByRole("navigation", { name: "工作区设置", exact: true }).getByRole("button", { name: "模型", exact: true }).click();
  const cards = page.locator(".hermes-model-card");
  await page.getByRole("region", { name: "DeepSeek", exact: true }).waitFor();
  assert.equal(await cards.count(), 3);
  assert.equal(await page.locator(".hermes-models-config .config-sidebar").count(), 0);
  await page.screenshot({ path: join(out, "model-cards-desktop.png") });
  const custom = page.getByRole("region", { name: "自定义接口", exact: true });
  await custom.getByRole("button", { name: "自定义接口 的模型", exact: true }).click();
  await page.getByRole("listbox", { name: "自定义接口 的模型", exact: true }).waitFor();
  await page.screenshot({ path: join(out, "model-cards-dropdown.png") });
  const listbox = page.getByRole("listbox", { name: "自定义接口 的模型", exact: true });
  await listbox.getByRole("textbox").fill("shared-model");
  await listbox.getByRole("option", { name: "shared-model", exact: true }).click();
  await custom.locator(".is-current").waitFor();
  assert.equal(writes.filter(row => row.path === "/api/model/set").length, 0);
  await custom.getByRole("button", { name: "fixture-model-5", exact: true }).click();
  await custom.getByRole("button", { name: "设为默认", exact: true }).click();
  await page.getByText("默认模型已更新", { exact: true }).waitFor();
  assert.deepEqual(writes.find(row => row.path === "/api/model/set").body, { scope: "main", provider: "custom-fixture", model: "fixture-model-5" });
  await custom.getByRole("button", { name: "当前默认", exact: true }).waitFor();
  assert.equal(await custom.getByRole("button", { name: "当前默认", exact: true }).isDisabled(), true);
  await page.getByLabel("搜索提供商或模型", { exact: true }).fill("deepseek-reasoner");
  assert.equal(await cards.count(), 1);
  await page.getByLabel("搜索提供商或模型", { exact: true }).fill("");
  await custom.getByRole("button", { name: "刷新 自定义接口 的模型", exact: true }).click();
  await page.getByText("已获取 87 个模型", { exact: true }).waitFor();
  await custom.getByRole("button", { name: "编辑 自定义接口", exact: true }).click();
  assert.equal(await page.getByLabel("提供商接口密钥", { exact: true }).inputValue(), "");
  await page.getByLabel("提供商名称", { exact: true }).fill("修改中的名称");
  page.once("dialog", dialog => dialog.dismiss());
  await page.getByRole("button", { name: "返回模型列表", exact: true }).click();
  assert.equal(await page.getByLabel("提供商名称", { exact: true }).inputValue(), "修改中的名称");
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "返回模型列表", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(out, "model-cards-mobile.png") });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await custom.getByRole("button", { name: "自定义接口 的模型", exact: true }).click();
  await page.getByRole("listbox", { name: "自定义接口 的模型", exact: true }).waitFor();
  const bounds = await page.getByRole("listbox", { name: "自定义接口 的模型", exact: true }).boundingBox();
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390);
  await page.screenshot({ path: join(out, "model-cards-mobile-dropdown.png") });
  assert.deepEqual(errors, []);
  console.log("PASS: provider cards, searchable model dropdown, provider-preserving quick switch, explicit default, refresh, dirty guard and mobile layout. Fixtures only.");
} finally { await browser.close(); }
